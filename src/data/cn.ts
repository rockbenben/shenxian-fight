/**
 * 中文序数：关卡是「第三关」而不是「第 3 关」——阿拉伯数字在这套排印里是外来物。
 *
 * 这张表原来有两份：`ui/theme.ts` 里一份（给选人/结算用），`ui/records.ts` 的
 * `summary()` 里又一份（'一二三四五六七八九十' 直接切下标）。同一个规则写两遍，
 * 迟早对不上——而这个项目在"规则被抄成两份"上栽过不止六次。
 * 收在这里而不是留在 ui/：`data/traits.ts` 那句「三记必杀全是箭」也要用它，
 * 而数据层不能反过来引 UI 层。
 *
 * 表长到十。原来只到六、注释写着"关卡最多四关，多出两个是余量"——
 * 阶梯改成六关之后余量正好用光，再加一关就会静默回落成阿拉伯数字。
 * 越界回落到阿拉伯数字而不是 undefined（标题页踩过一次：关序号写死「一二三四」，
 * 第五关显示成 undefined，单元测试全绿、打开浏览器才看见）。
 */
export const CN_NUM = ['一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];
/** n 是 0 起的下标：cn(2) = 「三」 */
export const cn = (n: number): string => CN_NUM[n] ?? String(n + 1);
